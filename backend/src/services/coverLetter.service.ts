import { BadRequestError } from "../utils/errors";

export type CoverLetterStyle = "CLASSIC" | "MODERN" | "CREATIVE" | "MINIMALIST";

export interface GenerateCoverLetterArgs {
  userId: string;
  jobTitle: string;
  companyName: string;
  jobDescription?: string;
  style: CoverLetterStyle;
}

export interface RenderCoverLetterArgs {
  fullName: string;
  email: string;
  phoneNumber?: string;
  headline?: string;
  style: CoverLetterStyle;
  content: string;
  jobTitle: string;
  companyName: string;
  themeColor?: string;
}

// Map styles to theme colors if applicable
const STYLE_COLOR_MAP: Record<CoverLetterStyle, string> = {
  CLASSIC: "#1e293b",
  MODERN: "#2563eb",
  CREATIVE: "#d97706",
  MINIMALIST: "#111111",
};

export async function composeCoverLetter(args: GenerateCoverLetterArgs): Promise<string> {
  const { userId, jobTitle, companyName, jobDescription, style } = args;

  if (!jobTitle.trim() || !companyName.trim()) {
    throw new BadRequestError("Job title and company name are required.");
  }

  // Fetch candidate's background data
  const data = await getResumeData(userId);
  const { user, experiences, projects, educations, socialLinks } = data;
  const profile = user.profile;

  // Format experience bullet summaries for prompt injection
  const experienceSummary = experiences
    .map((exp) => {
      const bullets = Array.isArray(exp.bullets) ? (exp.bullets as string[]) : [];
      return `- ${exp.role} at ${exp.company} (${exp.startDate.getFullYear()} - ${exp.endDate ? exp.endDate.getFullYear() : "Present"}):\n${bullets.map(b => `  * ${b}`).join("\n")}`;
    })
    .join("\n\n");

  // Format projects
  const projectSummary = projects
    .map((p) => `- Project: ${p.title} (${p.description || ""})`)
    .join("\n");

  // Format skills
  const skillsList = profile?.techStacks
    ? profile.techStacks.map((s) => s.tech.name).join(", ")
    : "";

  const systemPrompt = `You are an elite, persuasive career consultant and cover letter writer. 
Write a highly targeted, professional, and quantified cover letter that perfectly aligns the candidate's background with the job description.
Follow these rules strictly:
1. Address the hiring manager or recruitment team professionally.
2. Ensure the entire cover letter (including salutation, body, and sign-off) is between 300 to 400 words total, structured as 3-4 professional, impactful paragraphs:
   - Paragraph 1: Catchy opening identifying the role of "${jobTitle}" at "${companyName}", and why the candidate is exceptionally excited.
   - Paragraph 2: Core technical/analytical match highlighting 1-2 key, highly quantified achievements from their experience.
   - Paragraph 3: Cultural fit, soft skills, and alignment with the role's requirements.
   - Paragraph 4: Enthusiastic closing call-to-action requesting an interview.
3. Match the chosen tone/style:
   - CLASSIC: Formal, elegant, traditional, and highly professional.
   - MODERN: Direct, technical, bold, and high-impact.
   - CREATIVE: Dynamic, narrative, passionate, and slightly bold.
   - MINIMALIST: Short, punchy, laser-focused on core strengths.
4. Output ONLY the raw cover letter body text (no address blocks, dates, header details, or footer sign-offs in the generated string, as they are automatically generated by the layout templates). Start directly with 'Dear [Hiring Manager/Team],' and end with the closing sign-off and candidate's name.`;

  const userPrompt = [
    `Please compose a tailored cover letter for:`,
    `Role: ${jobTitle}`,
    `Company: ${companyName}`,
    jobDescription ? `Job Description: ${jobDescription}` : `No detailed job description provided. Align with standard requirements for this role.`,
    `Candidate Profile:`,
    `- Name: ${profile?.displayName || user.fullName}`,
    `- Headline: ${profile?.headline || "Software Engineer"}`,
    `- Professional Bio: ${profile?.bio || ""}`,
    `- Top Skills: ${skillsList}`,
    `Candidate Experience:\n${experienceSummary}`,
    `Candidate Projects:\n${projectSummary}`,
    `Style Preference: ${style}`,
  ].join("\n\n");

  const letterText = await nimChat([
    { role: "system", content: systemPrompt },
    { role: "user", content: userPrompt }
  ], { maxTokens: 1000, temperature: 0.7 });

  return letterText.trim();
}

function escapeHtml(input: string | null | undefined) {
  if (!input) return "";
  return input
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function formatLetterContentHtml(content: string): string {
  // Split paragraphs by double newlines and wrap in <p> tags
  return content
    .split(/\n\s*\n/)
    .map(p => `<p style="margin-bottom: 12px;">${escapeHtml(p.trim())}</p>`)
    .join("\n");
}

