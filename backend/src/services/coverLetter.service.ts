export async function renderCoverLetterPdf(args: RenderCoverLetterArgs): Promise<Buffer> {
  const html = buildCoverLetterHtml(args);
  const isLocal = process.env.NODE_ENV !== "production";

  const browser = await puppeteer.launch({
    args: chromium.args,
    defaultViewport: null,
    executablePath: isLocal
      ? (process.env.CHROME_EXECUTABLE_PATH ?? await chromium.executablePath())
      : await chromium.executablePath(),
    headless: true,
  });

  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 816, height: 1056 });
    await page.setContent(html, { waitUntil: "networkidle2" });
    const pdf = await page.pdf({
      printBackground: true,
      preferCSSPageSize: true,
    });
    return Buffer.from(pdf);
  } finally {
    await browser.close();
  }
}

export async function renderCoverLetterDocx(args: RenderCoverLetterArgs): Promise<Buffer> {
  const { fullName, email, phoneNumber, headline, content, jobTitle, companyName } = args;
  const dateStr = new Date().toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric"
  });

  const children: Paragraph[] = [];

  // Header Details (Classic Style for DOCX)
  children.push(
    new Paragraph({
      alignment: AlignmentType.RIGHT,
      spacing: { after: 120 },
      children: [
        new TextRun({ text: fullName, bold: true, size: 24 }),
        new TextRun({ text: headline ? `\n${headline}` : "", italics: true, size: 16 }),
        new TextRun({ text: `\nEmail: ${email}`, size: 16 }),
        new TextRun({ text: phoneNumber ? `\nPhone: ${phoneNumber}` : "", size: 16 }),
      ],
    })
  );

  // Date
  children.push(
    new Paragraph({
      spacing: { after: 120 },
      children: [new TextRun({ text: dateStr, size: 18 })],
    })
  );

  // Recipient
  children.push(
    new Paragraph({
      spacing: { after: 120 },
      children: [
        new TextRun({ text: "Hiring Manager / Recruitment Team\n", size: 18 }),
        new TextRun({ text: companyName, size: 18 }),
      ],
    })
  );

  // Subject
  children.push(
    new Paragraph({
      spacing: { after: 180 },
      children: [
        new TextRun({ text: `SUBJECT: APPLICATION FOR THE POSITION OF ${jobTitle.toUpperCase()}`, bold: true, size: 18 }),
      ],
    })
  );

  // Body content split by paragraph breaks
  const paragraphs = content.split(/\n\s*\n/);
  paragraphs.forEach((p) => {
    children.push(
      new Paragraph({
        spacing: { after: 120 },
        children: [new TextRun({ text: p.trim(), size: 18 })],
      })
    );
  });

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: { top: 1000, right: 1000, bottom: 1000, left: 1000 }, // 0.7 inch
          },
        },
        children,
      },
    ],
  });

  return await Packer.toBuffer(doc);
}
